#!/usr/bin/env node
/**
 * Build the hub:
 *   1. obfuscate every payload in hub.config.json
 *   2. minify + embed the loader core (VM + SHA-256 + guards + flow)
 *   3. emit data/generated.mjs (imported by the API functions)
 *
 * Payloads stay as obfuscated plaintext on the server; the actual delivery
 * encryption + VM layout is generated per session by /api/payload.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { obfuscateLua, minifyLua } from "../lib/lua-obfuscate.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const config = JSON.parse(readFileSync(join(root, "hub.config.json"), "utf8"));
const ID_RE = /^[a-z0-9][a-z0-9_-]{0,63}$/;

const scripts = [];
const seen = new Set();

for (const entry of config.scripts) {
  for (const field of ["id", "file", "name", "description", "author", "version"]) {
    if (!entry[field] || typeof entry[field] !== "string") {
      throw new Error(`hub.config.json: script entry missing "${field}" (${entry.id || "?"})`);
    }
  }
  if (!ID_RE.test(entry.id)) throw new Error(`invalid script id: ${entry.id}`);
  if (seen.has(entry.id)) throw new Error(`duplicate script id: ${entry.id}`);
  seen.add(entry.id);

  const source = readFileSync(join(root, entry.file), "utf8");
  const { code, stats } = obfuscateLua(source, { chunkName: entry.id });
  scripts.push({
    id: entry.id,
    name: entry.name,
    description: entry.description,
    author: entry.author,
    version: entry.version,
    tags: Array.isArray(entry.tags) ? entry.tags.map(String) : [],
    code,
    size: { source: stats.bytesIn, packed: stats.bytesOut, strings: stats.strings },
  });
}

const coreParts = ["lua/vm.lua", "lua/sha.lua", "lua/guard.lua", "lua/core.lua"].map((file) =>
  readFileSync(join(root, file), "utf8"),
);
const core = minifyLua(coreParts.join("\n"));
const runnerTpl = readFileSync(join(root, "lua/runner.tpl"), "utf8").trim();
const vmSource = minifyLua(readFileSync(join(root, "lua/vm.lua"), "utf8"));

const build = {
  at: new Date().toISOString(),
  version: createHash("sha256").update(core).digest("hex").slice(0, 12),
  scripts: scripts.length,
};

const payload = `// AUTO-GENERATED by tools/build.mjs — do not edit by hand.
export const BUILD = ${JSON.stringify(build, null, 2)};
export const CORE = ${JSON.stringify(core)};
export const RUNNER = { tpl: ${JSON.stringify(runnerTpl)}, vm: ${JSON.stringify(vmSource)} };
export const SCRIPTS = ${JSON.stringify(scripts, null, 2)};
`;

writeFileSync(join(root, "data", "generated.mjs"), payload);

const total = scripts.reduce(
  (acc, s) => ({ src: acc.src + s.size.source, packed: acc.packed + s.size.packed }),
  { src: 0, packed: 0 },
);
console.log(`core      ${core.length.toLocaleString()} bytes  build ${build.version}`);
for (const script of scripts) {
  console.log(
    `script    ${script.id.padEnd(16)} ${String(script.size.source).padStart(7)} -> ${String(script.size.packed).padStart(7)} bytes  (${script.size.strings} strings encoded)`,
  );
}
console.log(`payloads  ${total.src.toLocaleString()} -> ${total.packed.toLocaleString()} bytes`);
